const DEFAULT_NOTIFICATION_SWEEP_CRON_EXPRESSION = '0 * * * * *';
const DEFAULT_NOTIFICATION_SWEEP_PENDING_THRESHOLD_MS = 120000;
const DEFAULT_NOTIFICATION_SWEEP_MAX_ATTEMPTS = 12;
const DEFAULT_NOTIFICATION_SWEEP_BATCH_SIZE = 500;
const DEFAULT_NOTIFICATION_RETRY_BASE_DELAY_MS = 60_000;
const DEFAULT_NOTIFICATION_RETRY_MAX_DELAY_MS = 1_800_000;
const DEFAULT_NOTIFICATION_SWEEP_LEASE_MS = 300_000;
const DEFAULT_NOTIFICATION_SWEEP_MAX_RETRY_BACKLOG = 20;

function resolvePositiveInt(envName: string, defaultValue: number): number {
  const parsed = parseInt(process.env[envName] ?? '', 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : defaultValue;
}

export const NOTIFICATION_SWEEP_CRON_EXPRESSION =
  process.env.NOTIFICATION_SWEEP_CRON_EXPRESSION ??
  DEFAULT_NOTIFICATION_SWEEP_CRON_EXPRESSION;

export const NOTIFICATION_SWEEP_PENDING_THRESHOLD_MS = resolvePositiveInt(
  'NOTIFICATION_SWEEP_PENDING_THRESHOLD_MS',
  DEFAULT_NOTIFICATION_SWEEP_PENDING_THRESHOLD_MS
);

export const NOTIFICATION_SWEEP_MAX_ATTEMPTS = resolvePositiveInt(
  'NOTIFICATION_SWEEP_MAX_ATTEMPTS',
  DEFAULT_NOTIFICATION_SWEEP_MAX_ATTEMPTS
);

export const NOTIFICATION_SWEEP_BATCH_SIZE = resolvePositiveInt(
  'NOTIFICATION_SWEEP_BATCH_SIZE',
  DEFAULT_NOTIFICATION_SWEEP_BATCH_SIZE
);

export const NOTIFICATION_RETRY_BASE_DELAY_MS = resolvePositiveInt(
  'NOTIFICATION_RETRY_BASE_DELAY_MS',
  DEFAULT_NOTIFICATION_RETRY_BASE_DELAY_MS
);

export const NOTIFICATION_RETRY_MAX_DELAY_MS = resolvePositiveInt(
  'NOTIFICATION_RETRY_MAX_DELAY_MS',
  DEFAULT_NOTIFICATION_RETRY_MAX_DELAY_MS
);

export const NOTIFICATION_SWEEP_LEASE_MS = resolvePositiveInt(
  'NOTIFICATION_SWEEP_LEASE_MS',
  DEFAULT_NOTIFICATION_SWEEP_LEASE_MS
);

export const NOTIFICATION_SWEEP_MAX_RETRY_BACKLOG = resolvePositiveInt(
  'NOTIFICATION_SWEEP_MAX_RETRY_BACKLOG',
  DEFAULT_NOTIFICATION_SWEEP_MAX_RETRY_BACKLOG
);
